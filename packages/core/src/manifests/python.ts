/**
 * Whether a discovered `.txt` file is a requirements file at all.
 *
 * `requirements.txt`, `requirements-<x>.txt` and `requirements_<x>.txt`
 * anywhere, and any `.txt` inside a `requirements/` directory except the files
 * that live beside requirements without being one: a README or licence, notes,
 * and constraints files, which pin versions and install nothing.
 */
export function isRequirementsFile(path: string): boolean {
  const parts = path.split('/');
  const file = parts.at(-1) ?? '';
  if (!file.toLowerCase().endsWith('.txt')) return false;
  if (/^constraints/i.test(file)) return false;
  if (/^requirements([-_.].*)?\.txt$/i.test(file)) return true;
  return (
    parts.at(-2) === 'requirements' &&
    !/^(readme|license|licence|notes?|changelog|constraints)/i.test(file)
  );
}

/** `requirements-dev.txt`, `requirements_test.txt`, `requirements/lint.txt`. */
export function isDevRequirementsFile(path: string): boolean {
  const file = path.split('/').pop() ?? '';
  const stem = file.replace(/\.txt$/i, '').replace(/^requirements[-_.]?/i, '');
  return stem.split(/[-_.]/).some((part) => DEV_NAME.test(part)) && stem !== '';
}

/** The header pip-compile and `uv pip compile` write above their output. */
const COMPILED_HEADER = /autogenerated by (?:pip-compile|uv via)/i;

/**
 * A `# via` entry naming the file a package was declared in, not a package:
 * `-r requirements.in`, or `my-app (pyproject.toml)` -- in any directory, and
 * with a dependency group after a colon, as `(backend/pyproject.toml:dev)`.
 */
const SOURCE_ENTRY =
  /^-r\s+\S|\((?:[^()]*\/)?(?:pyproject\.toml|setup\.py|setup\.cfg)(?::[^()]*)?\)\s*$/;

/**
 * Read a requirements file.
 *
 * A compiled file is a lockfile, and its packages are split into declared and
 * transitive by their `# via` annotations. pip-compile and uv write those in
 * three shapes: inline (`boto3==1  # via langchain-aws`, where older pip-tools
 * separates several with commas), on the next line (`    # via boto3`), or as
 * a bare `    # via` followed by one `    #   <entry>` line per entry. An entry
 * is either a package or the source that declared it -- `-r requirements.in`,
 * or `my-app (pyproject.toml)`. A `-c` entry only constrains a version.
 *
 * A file counts as compiled when it carries the tool's header, or when every
 * requirement in it is annotated and at least one annotation names a source.
 * A hand-written file whose comments happen to start with "via" therefore
 * cannot make its dependencies transitive and silent.
 *
 * A parent that is not itself a requirement in the file is taken as a source.
 * It is usually the project, installed by an `-e file:.` line that carries no
 * name, and treating it as a package would drop every SDK the project declared.
 */
export function parseRequirementsTxt(
  text: string,
  path: string,
  dev = isDevRequirementsFile(path),
): ManifestParseResult {
  const index = new LineIndex(text);
  const found: {
    at: number;
    length: number;
    name: string;
    spec: string;
    /** `null` when the requirement carries no `# via` annotation at all. */
    via: string[] | null;
  }[] = [];
  let header = false;

  let offset = 0;
  // The previous line ended in `\`, so this one continues it -- in pip-compile
  // output that is a `--hash` option, never a new requirement.
  let continuation = false;
  // The requirement an indented `# via` line annotates. It survives the hash
  // continuations that `--generate-hashes` puts between the two.
  let current: (typeof found)[number] | null = null;
  let inViaBlock = false;
  for (const physical of text.split('\n')) {
    const lineOffset = offset;
    offset += physical.length + 1;
    const raw = physical.endsWith('\r') ? physical.slice(0, -1) : physical;
    const continued = continuation;
    continuation = raw.trimEnd().endsWith('\\');
    if (continued) continue;

    const comment = /^(\s*)#\s?(.*)$/.exec(raw);
    if (comment) {
      const [, indent = '', body = ''] = comment;
      if (COMPILED_HEADER.test(body)) header = true;
      // A column-0 comment ends an annotation block. pip-compile's trailer
      // ("The following packages are considered to be unsafe") is one.
      if (indent === '' || !current) {
        current = null;
        inViaBlock = false;
        continue;
      }
      const via = /^via\b\s*(.*)$/.exec(body.trim());
      if (via) {
        current.via ??= [];
        current.via.push(...viaEntries(via[1] ?? ''));
        inViaBlock = (via[1] ?? '').trim() === '';
      } else if (inViaBlock && body.trim() !== '') {
        current.via?.push(body.trim());
      }
      continue;
    }
    if (raw.trim() === '') {
      current = null;
      inViaBlock = false;
      continue;
    }

    // A comment starts at `#` at the start of the line or after whitespace;
    // `#` inside a URL fragment (`…#egg=name`) is not one, but such a line is
    // a direct reference with no leading name and is refused below anyway.
    const inline = /(?:^|\s)#\s*(.*)$/.exec(raw)?.[1] ?? '';
    const line = raw.replace(/(^|\s)#.*$/, '').replace(/\\\s*$/, '');
    current = null;
    inViaBlock = false;
    if (line.trim() === '' || line.trim().startsWith('-')) continue;

    const requirement = requirementName(line);
    if (!requirement) continue;
    const written = line.slice(requirement.at).match(/^[A-Za-z0-9._-]+/)?.[0] ?? '';
    const inlineVia = /^via\b\s*(.*)$/.exec(inline.trim());
    current = {
      at: lineOffset + requirement.at,
      length: written.length,
      name: requirement.name,
      spec: requirement.spec,
      via: inlineVia ? viaEntries(inlineVia[1] ?? '') : null,
    };
    found.push(current);
  }

  const inFile = new Set(found.map((f) => f.name));
  const packageEntry = (entry: string) =>
    !entry.startsWith('-') && !SOURCE_ENTRY.test(entry)
      ? normalisePypiName(entry.split(/\s/)[0] ?? entry)
      : null;
  const isSource = (entry: string) => {
    if (SOURCE_ENTRY.test(entry)) return true;
    const name = packageEntry(entry);
    return name !== null && !inFile.has(name);
  };
  const annotated = found.filter((f) => f.via !== null).length;
  const compiled =
    header ||
    (found.length > 0 && annotated === found.length && found.some((f) => f.via?.some(isSource)));
  const errors: ManifestParseResult['errors'] = [];
  // pip-compile --no-annotate: a lockfile, but one that no longer says which
  // packages were asked for. Declaring all of them would be A10 again.
  const unannotated = header && annotated === 0 && found.length > 0;
  if (unannotated) {
    errors.push({
      file: path,
      message:
        'compiled without `# via` annotations, so its declared packages cannot be told from transitive ones; none is attributed. Scan the source file it was compiled from.',
      fatal: false,
    });
  }

  const dependencies = found.map((f) => {
    const direct = !unannotated && (!compiled || f.via === null || f.via.some(isSource));
    const parents = direct
      ? []
      : (f.via ?? []).map(packageEntry).filter((name): name is string => name !== null);
    return record(index, path, f.at, f.length, f.name, f.spec, dev, direct, parents);
  });
  return { dependencies, errors };
}

/** The entries of one `# via` line: `a, b`, `-r requirements.in`, or nothing. */
function viaEntries(text: string): string[] {
  return text
    .split(',')
    .map((entry) => entry.trim())
    .filter((entry) => entry !== '');
}

