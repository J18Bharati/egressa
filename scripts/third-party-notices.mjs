function main() {
  const packages = new Map();
  for (const bundle of BUNDLES) {
    const path = join(root, bundle);
    if (!existsSync(path)) {
      console.error(`third-party-notices: ${bundle} is missing -- run the package builds first`);
      process.exit(1);
    }
    for (const [name, dir] of inlinedPackages(readFileSync(path, 'utf8'))) {
      packages.set(name, join(root, dir));
    }
  }

  const sections = [...packages.entries()]
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([name, dir]) => {
      const pkg = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'));
      const repo = typeof pkg.repository === 'string' ? pkg.repository : pkg.repository?.url;
      return [
        `${name}@${pkg.version}`,
        `License: ${pkg.license}`,
        ...(repo ? [`Repository: ${repo}`] : []),
        '',
        licenceText(dir),
      ].join('\n');
    });

  const text = [
    'THIRD-PARTY NOTICES',
    '',
    'The published egressa and @egressa/mcp packages, and the CLI bundled in',
    'skill/privacy-review/bin/, include the following third-party software. Each',
    'is used under the licence reproduced below. This file is generated by',
    'scripts/third-party-notices.mjs from the bundles themselves.',
    '',
    ...sections.flatMap((s) => ['-'.repeat(78), '', s, '']),
    ...ADAPTED.flatMap((a) => ['-'.repeat(78), '', a.heading, ...a.detail, '', a.licence, '']),
  ].join('\n');
  writeFileSync(join(root, 'THIRD_PARTY_NOTICES'), `${text.trimEnd()}\n`);
  console.log(`third-party-notices: ${packages.size} packages -> THIRD_PARTY_NOTICES`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) main();
